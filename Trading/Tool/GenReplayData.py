def ts(date_str: str) -> int:
    """'2026-09-01 09:30' -> 毫秒时间戳（北京时间）"""
    dt = datetime.strptime(date_str, "%Y-%m-%d %H:%M").replace(tzinfo=CN_TZ)
    return int(dt.timestamp() * 1000)


def gen_day_klines(date: str, slots: list) -> list:
    """slots: [(time_str, open, high, low, close)]"""
    out = []
    for t_str, op, hi, lo, cl in slots:
        d = f"{date} {t_str}"
        out.append({
            "timestamp": ts(d),
            "date": d,
            "open": op,
            "high": hi,
            "low": lo,
            "close": cl,
            "vol": 2500,
        })
    return out


def find_bar(day_slots, t_str):
    for s in day_slots:
        if s[0] == t_str:
            return s
    raise ValueError("未找到 K 线: {}".format(t_str))


